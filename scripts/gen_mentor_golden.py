#!/usr/bin/env python3
"""Reference values for the indicators, coverage, conditions without evidence and relevance order, recomputed from
data/processed/experiments.csv with an INDEPENDENT implementation (it uses neither psi_queries nor src/backend).
Output: frontend/src/lib/mentor_golden.json. Compared by: the Vitest tests (TypeScript), tests/test_relevance_parity.py (backend
Python) and scripts/audit_numbers.py (which fails if the file does not match the data).
Usage: python scripts/gen_mentor_golden.py"""
from __future__ import annotations

import csv
import json
import os
import statistics  # noqa: F401  (kept in case it is extended)
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "frontend", "src", "lib", "mentor_golden.json")
PSI, TOL_O2, TOL_P, EPS = 14.6959, 0.01, 0.5, 1e-9
BANDS = [(0.0, 0.15, "<0.15"), (0.15, 0.18, "0.15-0.18"), (0.18, 0.21, "0.18-0.21"), (0.21, 0.24, "0.21-0.24"), (0.24, 1.01, ">=0.24")]
LEVELS = [("~0.7 atm", 0.6, 0.8), ("~1.0 atm", 0.9, 1.1), (">2 atm", 2.0, None)]
SCEN = {"earth_iss": (("point", 0.21), ("point", 14.7)), "lunar_challenge": (("min", 0.30), ("max", 10.2)),
        "lunar_nasa": (("point", 0.265), ("point", 10.2)), "exploration": (("point", 0.34), ("point", 8.2)), "suit": (("point", 1.0), ("point", 4.3))}


def load():
    rows = list(csv.DictReader(open(os.path.join(ROOT, "data", "processed", "experiments.csv"), newline="", encoding="utf-8")))
    for r in rows:
        for k in ("o2_fraction", "pressure_atm", "co2_fraction", "he_fraction", "burning_rate_mm2_s", "extinction_diameter_mm"):
            r[k] = float(r[k]) if r[k] not in ("", None) else None
    return rows


declared = lambda r: r["outcome"] not in ("", None) and r["outcome_source"] != "not_stated"


def complete(r):
    base = r["o2_fraction"] is not None and declared(r)
    if r["program"] == "FLEX":
        return bool(base and r["material_or_fuel"] and r["pressure_atm"] is not None and (r["burning_rate_mm2_s"] is not None or r["extinction_diameter_mm"] is not None))
    return bool(base and r["material_category"])


def band(o2):
    return next(l for lo, hi, l in BANDS if lo <= o2 < hi)


def level(a):
    return None if a is None else next((l for l, lo, hi in LEVELS if a >= lo and (hi is None or a < hi)), None)


def kind(r):
    return r["material_or_fuel"] if r["program"] == "FLEX" else r["material_category"]


def supp(r):
    return "he" if (r["he_fraction"] or 0) > 0 else "co2" if (r["co2_fraction"] or 0) > 0 else "none"


def delta(x, c):
    k, v = c
    return x - v if k == "point" else min(0.0, x - v) if k == "min" else max(0.0, x - v)


def within(d, tol, strict, k):
    return abs(d) <= tol + EPS if k == "point" else (abs(d) <= EPS if strict else abs(d) <= tol + EPS)


def relaxed(x, c, tol):
    k, v = c
    return abs(x - v) <= tol + EPS if k == "point" else x >= v - tol - EPS if k == "min" else x <= v + tol + EPS


def main():
    rows = load()
    cell_n = {}
    for r in rows:
        key = (r["program"], kind(r), band(r["o2_fraction"]), level(r["pressure_atm"]))
        cell_n[key] = cell_n.get(key, 0) + 1
    out = {"note": "Generated by scripts/gen_mentor_golden.py (independent recomputation from experiments.csv). Do not edit.",
           "completeness": {"tests": len(rows), "complete": sum(complete(r) for r in rows), "partial": sum(not complete(r) for r in rows),
                            "complete_ai_extracted": sum(complete(r) and r["outcome_source"] == "ai_extracted" for r in rows),
                            "by_program": {p: {"tests": sum(r["program"] == p for r in rows), "complete": sum(r["program"] == p and complete(r) for r in rows)} for p in ("FLEX", "BASS-II")}},
           "scenarios": {}}
    flex_fuels = sorted({r["material_or_fuel"] for r in rows if r["program"] == "FLEX"})
    materials = sorted({r["material_category"] for r in rows if r["program"] == "BASS-II"})
    air = {}
    with open(os.path.join(ROOT, "data", "processed", "bass2_tests.csv"), newline="", encoding="utf-8") as f:
        air = {x["test_id"]: float(x["ai_initial_air_speed_cm_s"]) for x in csv.DictReader(f) if x["ai_initial_air_speed_cm_s"] not in ("", None)}
    for sid, (o2c, pc) in SCEN.items():
        ok = lambda r: r["pressure_atm"] is not None and relaxed(r["o2_fraction"], o2c, TOL_O2) and relaxed(r["pressure_atm"] * PSI, pc, TOL_P)
        groups = [{"name": f, "n": sum(r["program"] == "FLEX" and r["material_or_fuel"] == f and ok(r) for r in rows)} for f in flex_fuels]
        groups += [{"name": m, "n": sum(r["program"] == "BASS-II" and r["material_category"] == m and relaxed(r["o2_fraction"], o2c, TOL_O2) for r in rows)} for m in materials]
        combos = [{"fuel": f, "supp": s, "n": sum(r["program"] == "FLEX" and r["material_or_fuel"] == f and supp(r) == s and ok(r) for r in rows)} for f in flex_fuels for s in ("none", "co2", "he")]
        ranked = []
        for r in rows:
            d_o2 = delta(r["o2_fraction"], o2c)
            n = cell_n[(r["program"], kind(r), band(r["o2_fraction"]), level(r["pressure_atm"]))]
            if r["pressure_atm"] is None:
                ranked.append((3, abs(d_o2) / TOL_O2, not declared(r), -n, r["program"], r["test_id"], "no_pressure")); continue
            d_p = delta(r["pressure_atm"] * PSI, pc)
            dist = max(abs(d_o2) / TOL_O2, abs(d_p) / TOL_P)
            ex = within(d_o2, TOL_O2, True, o2c[0]) and within(d_p, TOL_P, True, pc[0])
            ne = within(d_o2, TOL_O2, False, o2c[0]) and within(d_p, TOL_P, False, pc[0])
            cl = "exact" if ex else "near" if ne else "not_near"
            ranked.append(({"exact": 0, "near": 1, "not_near": 2}[cl], dist, not declared(r), -n, r["program"], r["test_id"], cl))
        ranked.sort()
        bass_air = [air[r["test_id"]] for r in rows if r["program"] == "BASS-II" and relaxed(r["o2_fraction"], o2c, TOL_O2) and r["test_id"] in air]
        out["scenarios"][sid] = {
            "coverage": {"x": sum(g["n"] > 0 for g in groups), "y": len(groups)},
            "no_evidence": {"k": sum(c["n"] == 0 for c in combos), "total": len(combos)},
            "relevance_counts": {c: sum(x[6] == c for x in ranked) for c in ("exact", "near", "not_near", "no_pressure")},
            "top10": [{"program": x[4], "test_id": x[5], "relevance": x[6]} for x in ranked[:10]],
            "airflow": {"min": min(bass_air), "max": max(bass_air), "n": len(bass_air)} if bass_air else None,
        }
    return out


if __name__ == "__main__":
    data = main()
    text = json.dumps(data, indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("mentor_golden.json", "up to date" if ok else "OUT OF DATE (run scripts/gen_mentor_golden.py)")
        sys.exit(0 if ok else 1)
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
